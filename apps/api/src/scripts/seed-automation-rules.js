/**
 * TriGyna Health & Wellness — Seed Canonical Automation Rules
 * Seeds production-ready automation workflows aligned with Docs/Sales Workflow.md
 */

const mongoose = require("mongoose");
const path = require("path");
require("dotenv").config({ path: path.join(__dirname, "../../../.env") });

const AutomationRule = require("../modules/integrations/automation-rule.model");
const User = require("../modules/users/user.model");

const MONGO_URI = process.env.MONGODB_URI || "mongodb://127.0.0.1:27017/trigyna";

async function seedAutomationRules() {
  console.log("--> Connecting to MongoDB:", MONGO_URI);
  await mongoose.connect(MONGO_URI);

  const admin = await User.findOne({ role: { $in: ["owner", "admin"] } });
  const adminId = admin ? admin._id : new mongoose.Types.ObjectId();

  const rulesData = [
    {
      name: "New Enquiry Lead Auto-Assignment & Queue Rule",
      description: "When an inbound lead is ingested, evaluates team workload and auto-assigns an active sales rep or routes to triage queue.",
      triggerEvent: "crm.lead.created",
      enabled: true,
      conditions: [],
      actions: [
        {
          type: "assign_lead",
          params: { strategy: "round_robin_lowest_load" },
        },
        {
          type: "notify_staff",
          params: {
            title: "New Inbound Lead Assigned",
            message: "A new prospective patient enquiry has been assigned to your sales queue.",
            role: "sales",
          },
        },
      ],
      quietHours: { enabled: false },
      frequencyCap: { maxExecutionsPerContact: 1, periodHours: 24 },
      createdBy: adminId,
    },
    {
      name: "Instant Multi-Channel Enquiry Acknowledgement",
      description: "Dispatches instant WhatsApp and email acknowledgement to patient confirming enquiry receipt and providing next steps.",
      triggerEvent: "crm.lead.created",
      enabled: true,
      conditions: [
        {
          field: "lead.source",
          operator: "exists",
          value: true,
        },
      ],
      actions: [
        {
          type: "send_whatsapp_template",
          params: {
            templateName: "welcome_consultation_offer",
            variables: ["{{fullName}}"],
          },
        },
        {
          type: "create_crm_activity",
          params: {
            action: "ACKNOWLEDGEMENT_DISPATCHED",
            details: "Instant WhatsApp & Email acknowledgement sent to prospect.",
          },
        },
      ],
      quietHours: { enabled: true, start: "22:00", end: "08:00", timezone: "Asia/Kolkata" },
      frequencyCap: { maxExecutionsPerContact: 1, periodHours: 24 },
      createdBy: adminId,
    },
    {
      name: "First-Contact SLA & Due Follow-up Alert",
      description: "Monitors response deadlines. Triggers an escalation alert when a lead follow-up task is due or passes SLA window.",
      triggerEvent: "crm.followup.due",
      enabled: true,
      conditions: [],
      actions: [
        {
          type: "notify_staff",
          params: {
            title: "Follow-up Due: High Priority Prospect",
            message: "Scheduled follow-up deadline reached. Please check in with patient.",
            role: "sales",
          },
        },
        {
          type: "create_crm_activity",
          params: {
            action: "SLA_REMINDER_TRIGGERED",
            details: "Automated SLA reminder pushed to sales representative.",
          },
        },
      ],
      quietHours: { enabled: false },
      frequencyCap: { maxExecutionsPerContact: 3, periodHours: 24 },
      createdBy: adminId,
    },
    {
      name: "Assisted Checkout & Payment Link Dispatch",
      description: "When an official order or invoice is generated by Sales Executive, dispatches secure Razorpay checkout link.",
      triggerEvent: "invoice.issued",
      enabled: true,
      conditions: [
        {
          field: "invoice.status",
          operator: "equals",
          value: "pending",
        },
      ],
      actions: [
        {
          type: "send_whatsapp_text",
          params: {
            template: "Hello {{patientName}}, your official TriGyna care plan bill #{{invoiceNumber}} for ₹{{totalAmount}} is ready. Pay securely online via Razorpay.",
          },
        },
        {
          type: "create_crm_activity",
          params: {
            action: "CHECKOUT_LINK_SHARED",
            details: "Automated payment link dispatched via verified WhatsApp channel.",
          },
        },
      ],
      quietHours: { enabled: false },
      frequencyCap: { maxExecutionsPerContact: 2, periodHours: 24 },
      createdBy: adminId,
    },
    {
      name: "Payment Verified & Automated Patient Onboarding Trigger",
      description: "Upon verified Razorpay capture, updates order state, credits package session ledger, and initiates patient chart onboarding.",
      triggerEvent: "payment.captured",
      enabled: true,
      conditions: [],
      actions: [
        {
          type: "create_crm_activity",
          params: {
            action: "PAYMENT_CONVERTED_ONBOARDING",
            details: "Verified payment received. Patient chart synchronized and care handoff activated.",
          },
        },
        {
          type: "notify_staff",
          params: {
            title: "Payment Received & Onboarding Ready",
            message: "Patient payment captured successfully. Ready for clinical care handoff.",
            role: "sales",
          },
        },
      ],
      quietHours: { enabled: false },
      frequencyCap: { maxExecutionsPerContact: 1, periodHours: 24 },
      createdBy: adminId,
    },
    {
      name: "Consultation Booking & Video Link Dispatch",
      description: "When doctor consultation is confirmed, sends Google Meet / Zoom link and calendar reminder directly to patient.",
      triggerEvent: "appointment.confirmed",
      enabled: true,
      conditions: [],
      actions: [
        {
          type: "send_whatsapp_template",
          params: {
            templateName: "booking_confirmed",
            variables: ["{{patientName}}", "{{doctorName}}", "{{appointmentDate}}", "{{startTime}}", "{{mode}}"],
          },
        },
        {
          type: "notify_staff",
          params: {
            title: "Appointment Confirmed",
            message: "Doctor consultation confirmed and video consultation link dispatched.",
            role: "sales",
          },
        },
      ],
      quietHours: { enabled: false },
      frequencyCap: { maxExecutionsPerContact: 2, periodHours: 24 },
      createdBy: adminId,
    },
  ];

  for (const rule of rulesData) {
    const existing = await AutomationRule.findOne({ name: rule.name });
    if (!existing) {
      await AutomationRule.create(rule);
      console.log(`  [+ Created] Rule: ${rule.name}`);
    } else {
      existing.triggerEvent = rule.triggerEvent;
      existing.actions = rule.actions;
      existing.conditions = rule.conditions;
      existing.enabled = true;
      await existing.save();
      console.log(`  [~ Updated] Rule: ${rule.name}`);
    }
  }

  const count = await AutomationRule.countDocuments();
  console.log(`--> Total active automation rules in DB: ${count}`);
  await mongoose.disconnect();
}

seedAutomationRules()
  .then(() => {
    console.log("Automation rules seeding completed successfully.");
    process.exit(0);
  })
  .catch((err) => {
    console.error("Seeding error:", err);
    process.exit(1);
  });

